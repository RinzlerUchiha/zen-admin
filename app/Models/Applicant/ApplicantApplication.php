<?php

namespace App\Models\Applicant;

use Illuminate\Database\Eloquent\Model;

/**
 * One application (tblapp_applications): an applicant's relationship with a
 * single job posting, as HR sees it.
 *
 * What a status means comes from config/applications.php, which mirrors the
 * applicant portal's copy. Closing, withdrawal, Not Selected and the Candidate
 * Pool all belong to an application — never to the applicant as a whole, whose
 * other applications carry on unaffected.
 */
class ApplicantApplication extends Model
{
    protected $connection = 'applicant';
    protected $table = 'tblapp_applications';

    // open_posting_id is generated by the database from closed_at; writing it
    // is an error, so it can never be mass-assigned.
    protected $guarded = ['id', 'open_posting_id'];

    // Stored values. They are data: see config/applications.php.
    public const APPLIED = 'Applied';
    public const DOCUMENTS_COMPLETE = 'Documents Complete';
    public const WITHDRAWN = 'Withdrawn';
    public const NON_RESPONSIVE = 'Non-Responsive';
    public const NOT_SELECTED = 'Not Selected';

    /*
    | Actually hired, which for headcount purposes means ORIENTED -- not
    | offered, not signed. Recorded by hand because nothing in this system
    | observes an orientation.
    |
    | Deliberately an OPEN status (config/applications.php): requirements may
    | still be outstanding and the 201 handoff has not happened, so closing it
    | here would hide the work that remains. The value existed in the config
    | from the start; this constant was missing, which is why nothing could
    | refer to it.
    */
    public const HIRED = 'Hired';

    /* Did not get past screening or matching, so was never interviewed.
       Distinct from NOT_SELECTED, which means interviewed and not chosen:
       without the distinction no report can tell screening loss from
       interview loss. Carries no cooldown. */
    public const NOT_SHORTLISTED = 'Not Shortlisted';

    /* The applicant turned the offer down. Their decision, not HR's, which is
       why it is not NOT_SELECTED. Carries no cooldown. */
    public const OFFER_DECLINED = 'Offer Declined';

    /* Closed because HR recommended the applicant to another job post and an
       application was created there. Not a rejection; carries no cooldown. */
    public const RECOMMENDED = 'Recommended';

    protected $casts = [
        'applied_at' => 'datetime',
        'closed_at' => 'datetime',
    ];

    public function applicant()
    {
        return $this->belongsTo(ApplicantPersonal::class, 'app_id', 'app_id');
    }

    /* ---------------------------------------------------------------------
     * The status table
     * ------------------------------------------------------------------- */

    /**
     * What a status means, or null for a status the table does not list.
     * Matched case-insensitively, the way the database compares the column, so
     * PHP and SQL never disagree about a row.
     *
     * @return array{closed: bool, candidate_pool: bool}|null
     */
    public static function statusDefinition(?string $status): ?array
    {
        $statuses = config('applications.statuses', []);
        $status = trim((string) $status);

        if (isset($statuses[$status])) {
            return $statuses[$status];
        }

        foreach ($statuses as $key => $definition) {
            if (strcasecmp($key, $status) === 0) {
                return $definition;
            }
        }

        return null;
    }

    /** Stored values of every status that ends an application. */
    public static function closedStatuses(): array
    {
        return self::statusesWhere('closed');
    }

    /** Stored values of every status that retains the candidate for that application. */
    public static function candidatePoolStatuses(): array
    {
        return self::statusesWhere('candidate_pool');
    }

    private static function statusesWhere(string $flag): array
    {
        return array_keys(array_filter(
            config('applications.statuses', []),
            fn ($definition) => !empty($definition[$flag])
        ));
    }

    /** Ended. An unlisted status is treated as open. */
    public function getIsClosedAttribute(): bool
    {
        return (bool) (self::statusDefinition($this->status)['closed'] ?? false);
    }

    /** In the Candidate Pool for THIS application only. */
    public function getInCandidatePoolAttribute(): bool
    {
        return (bool) (self::statusDefinition($this->status)['candidate_pool'] ?? false);
    }

    /**
     * For HR's information: the first day the applicant may apply to the same
     * posting again, if this application's outcome started a cooldown and it
     * has not ended. Counted exactly as the applicant portal enforces it
     * (zen-applicants App\Services\ReapplicationPolicy): months from
     * config/applications.php 'cooldowns', without overflow, from the start of
     * that day. The portal is where applying happens; this only reports it.
     */
    public static function cooldownEndsFor(?string $status, $closedAt): ?\Illuminate\Support\Carbon
    {
        if (!$closedAt) {
            return null;
        }

        foreach (config('applications.cooldowns', []) as $key => $rule) {
            if (strcasecmp($key, trim((string) $status)) === 0 && (int) ($rule['months'] ?? 0) > 0) {
                $ends = \Illuminate\Support\Carbon::parse($closedAt)
                    ->addMonthsNoOverflow((int) $rule['months'])
                    ->startOfDay();

                return now()->lessThan($ends) ? $ends : null;
            }
        }

        return null;
    }

    public function scopeOpen($query)
    {
        return $query->whereNotIn('status', self::closedStatuses());
    }

    public function scopeClosed($query)
    {
        return $query->whereIn('status', self::closedStatuses());
    }

    /**
     * In the Candidate Pool, and actually available to be revisited.
     *
     * TWO QUESTIONS, NOT ONE
     *
     * The status answers what happened to THIS application: it ended in a way
     * that keeps the person worth seeing again. config/applications.php owns
     * that, and nothing here changes it.
     *
     * Availability is a question about the PERSON, and the status cannot
     * answer it. Somebody who withdrew from one posting while live on another
     * is mid-process, not a prospect -- and the pool exists to answer "who
     * have we met before who might suit this new post?". Offering them up
     * invites HR to recommend somebody into a second pipeline while the first
     * is still running.
     *
     * This matters most for Recommended, which is created by a recommendation
     * that has ALREADY produced a live application on the other posting. The
     * disposition stays pooled, and the row simply does not surface while that
     * application is open -- it returns, intact, the moment it closes.
     *
     * Kept here rather than in each caller so the page, the dashboard count
     * and anything added later cannot drift apart.
     */
    public function scopeInCandidatePool($query)
    {
        $table = $query->getQuery()->from ?: 'tblapp_applications';
        $alias = str_contains($table, ' as ')
            ? trim(explode(' as ', $table)[1])
            : $table;

        return $query->whereIn($alias . '.status', self::candidatePoolStatuses())
            ->whereNotExists(function ($q) use ($alias) {
                $q->from('tblapp_applications as pool_live')
                    ->whereColumn('pool_live.app_id', $alias . '.app_id')
                    ->whereNull('pool_live.closed_at');
            });
    }
}
