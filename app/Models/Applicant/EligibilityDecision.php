<?php

namespace App\Models\Applicant;

use Illuminate\Database\Eloquent\Model;

/**
 * HR's shortlisting decision on one application.
 *
 * The snapshot is the point. An application's status says where it ended up;
 * it cannot say what the system had advised at the time, whether HR agreed, or
 * why they did not — and those are the questions asked when a shortlist is
 * challenged. The specification, its classification and the applicant's own
 * profile all move underneath a decision, so the advice is stored as it stood.
 *
 * Corrections supersede rather than overwrite, following the pattern the
 * interview evaluations already use.
 */
class EligibilityDecision extends Model
{
    protected $connection = 'applicant';
    protected $table = 'tblapp_eligibility_decisions';

    // live_application_id is generated by the database from superseded_at;
    // writing it is an error, so it can never be mass-assigned.
    protected $guarded = ['id', 'live_application_id'];

    protected $casts = [
        'recommendation_snapshot' => 'array',
        'overrode' => 'boolean',
        'decided_at' => 'datetime',
        'superseded_at' => 'datetime',
    ];

    public const SHORTLISTED = 'shortlisted';
    public const NOT_SHORTLISTED = 'not_shortlisted';

    public function application()
    {
        return $this->belongsTo(ApplicantApplication::class, 'application_id');
    }

    /** The decision that stands, as opposed to one that was corrected. */
    public function scopeLive($query)
    {
        return $query->whereNull('superseded_at');
    }

    public function isLive(): bool
    {
        return $this->superseded_at === null;
    }
}
